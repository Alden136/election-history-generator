/**
 * Writes reference/formulas.md: every column's formulas, listed once per
 * distinct pattern. Rows that hold the same formula shifted down (the usual
 * "fill down") are collapsed into one entry with a row range.
 *
 * Run: node tools/list-formulas.ts
 */
import { writeFileSync } from 'node:fs';
import { colIndex, colName, loadSheet } from './sheet.ts';

const sheet = loadSheet();

/**
 * Rewrites relative cell references as offsets from the cell that holds the
 * formula, so that a formula filled down or across normalises to one string.
 * Absolute parts ($A, $1) are kept as written. Quoted strings are left alone.
 */
function normalise(formula: string, row: number, col: number): string {
  const parts = formula.split(/("(?:[^"]|"")*")/);
  return parts
    .map((part, i) => {
      if (i % 2 === 1) return part; // string literal
      return part.replace(
        /(\$?)([A-Z]{1,3})(\$?)(\d+)(?![\d(])/g,
        (_m, absCol: string, c: string, absRow: string, r: string) => {
          const cPart = absCol ? `$${c}` : `c${signed(colIndex(c) - col)}`;
          const rPart = absRow ? `$${r}` : `r${signed(Number(r) - row)}`;
          return `{${cPart},${rPart}}`;
        },
      );
    })
    .join('');
}

function signed(n: number): string {
  return n >= 0 ? `+${n}` : `${n}`;
}

interface Run {
  startRow: number;
  endRow: number;
  example: string;
}

const lines: string[] = [
  '# Formula listing',
  '',
  'Generated by `tools/list-formulas.ts` from the frozen sheet snapshot.',
  'Each entry shows the formula as written in the first row of a run; the',
  'rows in the run hold the same formula filled down.',
  '',
];

let formulaCells = 0;
let patterns = 0;
/** One line per run, whitespace collapsed: easier to search and diff. */
const compact: string[] = [];
/** Runs grouped by pattern across columns, so a formula filled right shows once. */
const unique = new Map<string, { example: string; where: string[] }>();

for (let col = 0; col < sheet.cols; col++) {
  const name = colName(col);
  const runs: Run[] = [];
  let lastKey: string | null = null;

  for (let row = 1; row <= sheet.rows; row++) {
    const f = sheet.formula(`${name}${row}`);
    if (f === null) {
      lastKey = null;
      continue;
    }
    formulaCells++;
    const key = normalise(f, row, col);
    const last = runs[runs.length - 1];
    if (last && key === lastKey && last.endRow === row - 1) {
      last.endRow = row;
    } else {
      runs.push({ startRow: row, endRow: row, example: f });
      patterns++;
    }
    lastKey = key;
  }

  if (runs.length === 0) continue;
  const header = [1, 2, 3]
    .map((r) => sheet.value(`${name}${r}`))
    .filter((v) => v !== null && v !== '')
    .join(' / ');
  lines.push(`## ${name}${header ? ` — ${header}` : ''}`, '');
  for (const run of runs) {
    const where =
      run.startRow === run.endRow ? `${run.startRow}` : `${run.startRow}–${run.endRow}`;
    lines.push(`**Rows ${where}**`, '', '```', `=${run.example}`, '```', '');
    compact.push(`${name} ${where} [${header}]: =${run.example.replace(/\s+/g, ' ')}`);
    const key = normalise(run.example, run.startRow, col).replace(/\s+/g, '');
    const seen = unique.get(key);
    if (seen) seen.where.push(`${name}${where}`);
    else unique.set(key, { example: run.example.replace(/\s+/g, ' '), where: [`${name}${where}`] });
  }
}

writeFileSync('reference/formulas.md', lines.join('\n'));
writeFileSync('reference/formulas-compact.txt', compact.join('\n'));
writeFileSync(
  'reference/formulas-unique.txt',
  [...unique.values()]
    .map((u) => {
      const first = u.where[0], last = u.where[u.where.length - 1];
      const span = u.where.length === 1 ? first : `${first} .. ${last} (${u.where.length} columns)`;
      return `${span}: =${u.example}`;
    })
    .join('\n'),
);
console.log(`${unique.size} unique formulas after collapsing across columns`);
console.log(
  `${sheet.rows} rows x ${sheet.cols} cols; ${formulaCells} formula cells; ${patterns} distinct runs`,
);
